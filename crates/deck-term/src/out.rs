//! The single path of every byte to the child ([`PtyOut`]), its sinks (the local PTY loop, a
//! remote host's writer thread, a gateway frontend's writer thread) and the detach bookkeeping
//! of dropped terminals ([`wait_detached`]).

use std::collections::VecDeque;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::mpsc;
use std::sync::{Arc, Condvar, Mutex, MutexGuard, OnceLock, PoisonError};
use std::thread::JoinHandle;
use std::time::{Duration, Instant};

use alacritty_terminal::event::WindowSize;

use crate::frontend::{FrontendCmd, InputMeta};
#[cfg(unix)]
use crate::pty::{LoopSender, Msg};
use crate::remote::RemoteCmd;
use crate::wake::Wake;

/// Quiet time kept after a write ending in a lone ESC before any terminal-generated byte (query
/// reply, focus report) may follow: apps parsing ESC with a timeout (omp) would merge `ESC` +
/// `ESC[I` (or a CPR) into one key.
const LONE_ESC_QUIET: Duration = Duration::from_millis(100);
/// Longest a dropped [`crate::Terminal`] waits for its queued input to be written.
const DETACH_FLUSH_TIMEOUT: Duration = Duration::from_secs(2);
/// Time a dropped [`crate::Terminal`] leaves the child to read just-written input before the
/// hang-up, counted from the last successful write.
const DETACH_GRACE: Duration = Duration::from_millis(50);
/// Poll step of [`wait_detached`].
const DETACH_POLL: Duration = Duration::from_millis(5);

/// Detach workers of dropped terminals (see [`wait_detached`]).
static DETACHING: Mutex<Vec<JoinHandle<()>>> = Mutex::new(Vec::new());

/// Remaining [`DETACH_GRACE`] at `now` after the last write at `last_write`.
fn grace_left(last_write: Option<Instant>, now: Instant) -> Duration {
    last_write.map_or(Duration::ZERO, |at| {
        DETACH_GRACE.saturating_sub(now.saturating_duration_since(at))
    })
}

/// Joins the finished handles in `handles`; true when none is left.
fn prune(handles: &mut Vec<JoinHandle<()>>) -> bool {
    let mut i = 0;
    while i < handles.len() {
        if handles[i].is_finished() {
            let _ = handles.swap_remove(i).join();
        } else {
            i += 1;
        }
    }
    handles.is_empty()
}

/// Polls `handles` until all workers finished or `timeout` passed; true when all finished.
fn wait_handles(handles: &Mutex<Vec<JoinHandle<()>>>, timeout: Duration) -> bool {
    let deadline = Instant::now() + timeout;
    loop {
        if prune(&mut handles.lock().unwrap_or_else(PoisonError::into_inner)) {
            return true;
        }
        let left = deadline.saturating_duration_since(Instant::now());
        if left.is_zero() {
            return false;
        }
        std::thread::sleep(left.min(DETACH_POLL));
    }
}

/// Registers a worker that must finish before the process exits (see [`wait_detached`]).
pub(crate) fn register_detaching(handle: JoinHandle<()>) {
    let mut pending = DETACHING.lock().unwrap_or_else(PoisonError::into_inner);
    prune(&mut pending);
    pending.push(handle);
}

/// Waits (at most `timeout`) for the detach workers of dropped [`crate::Terminal`]s (input
/// still in flight, remote detaches), so their bytes reach the children before the process
/// exits. Call it after the UI loop returned.
pub fn wait_detached(timeout: Duration) {
    wait_handles(&DETACHING, timeout);
}

/// Non-blocking input-delivery checkpoint. An acknowledgement means the local PTY write or
/// remote transport's `input` call succeeded; it is not confirmation that the application acted.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct InputProgress {
    pub queued: u64,
    pub acknowledged: u64,
    pub failed: bool,
    pub closed: bool,
}

/// Input bytes handed on to the child so far and when the last write call returned (see
/// [`crate::Terminal`]'s detach). Written by the local PTY writer or the remote writer thread.
#[derive(Default)]
pub(crate) struct WriteProgress {
    state: Mutex<Written>,
    changed: Condvar,
    failed: AtomicBool,
}

#[derive(Default)]
struct Written {
    bytes: u64,
    acknowledged: u64,
    last_at: Option<Instant>,
}

impl WriteProgress {
    pub(crate) fn record(&self, n: usize, success: bool) {
        let mut w = self.state.lock().unwrap_or_else(PoisonError::into_inner);
        w.bytes += n as u64;
        if !success {
            self.failed.store(true, Ordering::Release);
        } else if !self.failed.load(Ordering::Acquire) {
            w.acknowledged += n as u64;
        }
        w.last_at = Some(Instant::now());
        self.changed.notify_all();
    }

    fn acknowledgement(&self) -> (u64, bool) {
        let w = self.state.lock().unwrap_or_else(PoisonError::into_inner);
        (w.acknowledged, self.failed.load(Ordering::Acquire))
    }

    pub(crate) fn written(&self) -> u64 {
        self.state
            .lock()
            .unwrap_or_else(PoisonError::into_inner)
            .bytes
    }

    /// When the last write call returned.
    pub(crate) fn last_write(&self) -> Option<Instant> {
        self.state
            .lock()
            .unwrap_or_else(PoisonError::into_inner)
            .last_at
    }

    /// Blocks until at least `target` bytes were written or `timeout` passed; true on success.
    pub(crate) fn wait_for(&self, target: u64, timeout: Duration) -> bool {
        let w = self.state.lock().unwrap_or_else(PoisonError::into_inner);
        let (w, _) = self
            .changed
            .wait_timeout_while(w, timeout, |w| {
                w.bytes < target && !self.failed.load(Ordering::Acquire)
            })
            .unwrap_or_else(PoisonError::into_inner);
        w.bytes >= target
    }

    /// Input the frontend's owner refused: handled (for the detach flush), never acknowledged,
    /// and not a connection failure.
    pub(crate) fn record_refused(&self, n: usize) {
        let mut w = self.state.lock().unwrap_or_else(PoisonError::into_inner);
        w.bytes += n as u64;
        w.last_at = Some(Instant::now());
        self.changed.notify_all();
    }
}

/// Where [`PtyOut`] delivers bytes and control messages. Every sink is an ordered queue
/// drained by another thread, so the UI thread never blocks on child I/O.
pub(crate) enum Sink {
    /// The PTY loop (Unix local terminals).
    #[cfg(unix)]
    Local(LoopSender),
    /// The writer thread of a remote terminal (see [`crate::remote`]).
    Remote(mpsc::Sender<RemoteCmd>),
    /// The writer thread of a gateway frontend (see [`crate::frontend`]).
    Frontend(mpsc::Sender<FrontendCmd>),
}

impl Sink {
    /// `meta` travels only to a frontend's owner; the other sinks write the child directly.
    fn input(&self, bytes: Vec<u8>, meta: InputMeta) -> bool {
        match self {
            #[cfg(unix)]
            Sink::Local(s) => s.send(Msg::Input(bytes)),
            Sink::Remote(s) => s.send(RemoteCmd::Input(bytes)).is_ok(),
            Sink::Frontend(s) => s.send(FrontendCmd::Input(bytes, meta)).is_ok(),
        }
    }

    fn resize(&self, size: WindowSize) {
        match self {
            #[cfg(unix)]
            Sink::Local(s) => {
                s.send(Msg::Resize(size));
            }
            Sink::Remote(s) => drop(s.send(RemoteCmd::Resize(size))),
            Sink::Frontend(s) => drop(s.send(FrontendCmd::Resize(size))),
        }
    }

    fn palette(&self, palette: [[u8; 3]; 19]) {
        match self {
            // The local Term answers color queries itself (see `Terminal::poll`).
            #[cfg(unix)]
            Sink::Local(_) => {}
            Sink::Remote(s) => drop(s.send(RemoteCmd::Palette(palette))),
            Sink::Frontend(s) => drop(s.send(FrontendCmd::Palette(palette))),
        }
    }

    /// Ends the connection, keeping the child: local `Msg::Shutdown` (the PTY thread drops
    /// the Pty, which hangs up a tmux client), remote and frontend detach.
    fn detach(&self) {
        match self {
            #[cfg(unix)]
            Sink::Local(s) => {
                s.send(Msg::Shutdown);
            }
            Sink::Remote(s) => drop(s.send(RemoteCmd::Detach)),
            Sink::Frontend(s) => drop(s.send(FrontendCmd::Detach)),
        }
    }

    /// Ends the child: local `Msg::Shutdown` (SIGHUP), remote kill, frontend kill request.
    fn kill(&self) {
        match self {
            #[cfg(unix)]
            Sink::Local(s) => {
                s.send(Msg::Shutdown);
            }
            Sink::Remote(s) => drop(s.send(RemoteCmd::Kill)),
            Sink::Frontend(s) => drop(s.send(FrontendCmd::Kill)),
        }
    }
}

/// Terminal-generated bytes held back by the lone-ESC quiet time.
struct Deferred {
    bytes: Vec<u8>,
    /// A focus report (an opposite report queued later cancels it).
    focus: bool,
}

#[derive(Default)]
struct OutState {
    /// When the last [`PtyOut::write`] ended with an ESC byte (cleared by any other write).
    lone_esc_at: Option<Instant>,
    deferred: VecDeque<Deferred>,
    /// Input bytes handed to the sink so far.
    sent: u64,
    /// Killed, dropped or displaced: new bytes are discarded.
    closed: bool,
}

/// The single path of every byte to the child (UI thread, output thread, clipboard worker).
/// [`Self::write`] bytes go out at once. Terminal-generated bytes (query replies, focus
/// reports) never follow a lone ESC within [`LONE_ESC_QUIET`]: they queue in order and go out
/// once the quiet time passed (from [`crate::Terminal::poll`]; a repaint is requested) or
/// directly behind the next write that does not end with ESC. The lock makes "send + update
/// state" atomic, so no reply can slip between a lone ESC and the write ending it.
pub(crate) struct PtyOut {
    sink: OnceLock<Sink>,
    state: Mutex<OutState>,
    progress: Arc<WriteProgress>,
    wake: Wake,
}

impl PtyOut {
    pub(crate) fn new(progress: Arc<WriteProgress>, wake: Wake) -> PtyOut {
        PtyOut {
            sink: OnceLock::new(),
            state: Mutex::new(OutState::default()),
            progress,
            wake,
        }
    }

    /// Connects the sink (once; set before the output thread starts parsing, so no reply can
    /// be dropped).
    pub(crate) fn set_sink(&self, sink: Sink) {
        if self.sink.set(sink).is_err() {
            log::error!("terminal output sink connected twice");
        }
    }

    fn lock(&self) -> MutexGuard<'_, OutState> {
        self.state.lock().unwrap_or_else(PoisonError::into_inner)
    }

    pub(crate) fn is_closed(&self) -> bool {
        self.lock().closed || self.progress.failed.load(Ordering::Acquire)
    }

    pub(crate) fn input_progress(&self) -> InputProgress {
        let st = self.lock();
        let (acknowledged, failed) = self.progress.acknowledgement();
        InputProgress {
            queued: st.sent,
            acknowledged,
            failed,
            closed: st.closed,
        }
    }

    fn send(&self, st: &mut OutState, bytes: Vec<u8>, meta: InputMeta) {
        if self.progress.failed.load(Ordering::Acquire) {
            return;
        }
        if let Some(sink) = self.sink.get() {
            st.sent += bytes.len() as u64;
            if !sink.input(bytes, meta) {
                st.closed = true;
                self.progress.record(0, false);
            }
        }
    }

    fn flush_deferred(&self, st: &mut OutState) {
        while let Some(d) = st.deferred.pop_front() {
            self.send(st, d.bytes, InputMeta::default());
        }
    }

    /// Remaining quiet time after a write that ended with ESC (forgets the ESC once over).
    fn quiet_left(st: &mut OutState) -> Option<Duration> {
        let left = st
            .lone_esc_at
            .and_then(|at| LONE_ESC_QUIET.checked_sub(at.elapsed()))
            .filter(|d| !d.is_zero());
        if left.is_none() {
            st.lone_esc_at = None;
        }
        left
    }

    pub(crate) fn write(&self, bytes: &[u8], meta: InputMeta) {
        let mut st = self.lock();
        if st.closed || self.progress.failed.load(Ordering::Acquire) {
            return;
        }
        self.send(&mut st, bytes.to_vec(), meta);
        if bytes.last() == Some(&0x1b) {
            st.lone_esc_at = Some(Instant::now());
        } else {
            // The ESC is no longer lone: queued bytes may follow right behind these.
            st.lone_esc_at = None;
            self.flush_deferred(&mut st);
        }
    }

    /// A terminal-generated reply: sent now, or queued behind earlier ones in the quiet time.
    pub(crate) fn reply(&self, bytes: Vec<u8>) {
        self.emit(Deferred {
            bytes,
            focus: false,
        });
    }

    /// A focus report; within the quiet time an out/in pair cancels out.
    pub(crate) fn focus_report(&self, bytes: Vec<u8>) {
        self.emit(Deferred { bytes, focus: true });
    }

    /// Frontend: the view's focus, for the owner to report in its child's modes.
    pub(crate) fn frontend_focus(&self, focused: bool) {
        if !self.lock().closed
            && let Some(Sink::Frontend(s)) = self.sink.get()
        {
            let _ = s.send(FrontendCmd::Focus(focused));
        }
    }

    /// Frontend: the reply to the owner's outstanding OSC 52 read.
    pub(crate) fn clipboard_reply(&self, bytes: Vec<u8>) {
        if !self.lock().closed
            && let Some(Sink::Frontend(s)) = self.sink.get()
        {
            let _ = s.send(FrontendCmd::ClipboardReply(bytes));
        }
    }

    fn emit(&self, d: Deferred) {
        let mut st = self.lock();
        if st.closed {
            return;
        }
        match Self::quiet_left(&mut st) {
            Some(left) => {
                // A queued focus report is always the opposite one (reports fire on changes).
                let queued_focus = d.focus.then(|| st.deferred.iter().position(|q| q.focus));
                match queued_focus.flatten() {
                    Some(pos) => drop(st.deferred.remove(pos)),
                    None => st.deferred.push_back(d),
                }
                self.wake.after(left);
            }
            None => {
                self.flush_deferred(&mut st);
                self.send(&mut st, d.bytes, InputMeta::default());
            }
        }
    }

    /// Sends the queue once the quiet time passed (else re-arms a repaint).
    pub(crate) fn flush_due(&self) {
        let mut st = self.lock();
        if st.deferred.is_empty() {
            return;
        }
        match Self::quiet_left(&mut st) {
            Some(left) => self.wake.after(left),
            None => self.flush_deferred(&mut st),
        }
    }

    pub(crate) fn resize(&self, size: WindowSize) {
        if let Some(sink) = self.sink.get() {
            sink.resize(size);
        }
    }

    pub(crate) fn palette(&self, palette: [[u8; 3]; 19]) {
        if let Some(sink) = self.sink.get() {
            sink.palette(palette);
        }
    }

    /// Ends the connection without waiting for anything (see [`Sink::detach`]).
    pub(crate) fn shutdown(&self) {
        if let Some(sink) = self.sink.get() {
            sink.detach();
        }
    }

    /// Kill: stops at once, discarding queued bytes.
    pub(crate) fn kill(&self) {
        self.discard();
        if let Some(sink) = self.sink.get() {
            sink.kill();
        }
    }

    /// Another client took the remote session over: input stops and the connection ends.
    pub(crate) fn displaced(&self) {
        self.discard();
        self.shutdown();
    }

    fn discard(&self) {
        let mut st = self.lock();
        st.closed = true;
        st.deferred.clear();
    }

    /// Detach: stops accepting bytes; true while sent or queued bytes may not have reached
    /// the child yet (see [`Self::finish_detach`]).
    pub(crate) fn close(&self) -> bool {
        let mut st = self.lock();
        st.closed = true;
        if self.progress.failed.load(Ordering::Acquire) {
            st.deferred.clear();
            return false;
        }
        !st.deferred.is_empty()
            || self.progress.written() < st.sent
            || !grace_left(self.progress.last_write(), Instant::now()).is_zero()
    }

    /// Blocking (runs on a detach thread): sends the queue after the quiet time, waits until
    /// the sink wrote everything (bounded) plus a grace after the last write for the child to
    /// read it, then detaches.
    pub(crate) fn finish_detach(&self) {
        if self.progress.failed.load(Ordering::Acquire) {
            self.shutdown();
            return;
        }
        let left = Self::quiet_left(&mut self.lock());
        if let Some(left) = left {
            std::thread::sleep(left);
        }
        let target = {
            let mut st = self.lock();
            self.flush_deferred(&mut st);
            st.sent
        };
        self.progress.wait_for(target, DETACH_FLUSH_TIMEOUT);
        if !self.progress.failed.load(Ordering::Acquire) {
            std::thread::sleep(grace_left(self.progress.last_write(), Instant::now()));
        }
        self.shutdown();
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn grace_counts_from_last_write() {
        let t0 = Instant::now();
        assert_eq!(grace_left(None, t0), Duration::ZERO);
        // Sent long ago, but the writer finished just now: the full grace remains.
        assert_eq!(grace_left(Some(t0), t0), DETACH_GRACE);
        let ms = Duration::from_millis;
        assert_eq!(grace_left(Some(t0), t0 + ms(20)), DETACH_GRACE - ms(20));
        assert_eq!(grace_left(Some(t0), t0 + DETACH_GRACE), Duration::ZERO);
        assert_eq!(grace_left(Some(t0), t0 + ms(500)), Duration::ZERO);
        // A write stamped after `now` (clock read race) keeps the full grace.
        assert_eq!(grace_left(Some(t0 + ms(5)), t0), DETACH_GRACE);
    }

    #[test]
    fn wait_handles_joins_and_never_overruns_timeout() {
        let (release, gate) = mpsc::channel::<()>();
        let slow = std::thread::spawn(move || {
            let _ = gate.recv_timeout(Duration::from_secs(10));
        });
        let quick = std::thread::spawn(|| {});
        let handles = Mutex::new(vec![slow, quick]);
        let start = Instant::now();
        assert!(!wait_handles(&handles, Duration::from_millis(50)));
        let waited = start.elapsed();
        assert!(waited >= Duration::from_millis(50), "{waited:?}");
        assert!(waited < Duration::from_millis(500), "{waited:?}");
        // The finished worker was joined and pruned; the running one is kept.
        assert_eq!(handles.lock().expect("lock").len(), 1);
        release.send(()).expect("send");
        assert!(wait_handles(&handles, Duration::from_secs(5)));
        assert!(handles.lock().expect("lock").is_empty());
        assert!(wait_handles(&handles, Duration::ZERO));
    }
}
