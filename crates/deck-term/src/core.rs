/// Quiet time kept after a write ending in a lone ESC before any terminal-generated byte (query
/// reply, focus report) may follow: apps parsing ESC with a timeout (omp) would merge `ESC` +
/// `ESC[I` (or a CPR) into one key.
const LONE_ESC_QUIET: Duration = Duration::from_millis(100);
/// Longest a dropped [`Terminal`] waits for its queued input to be written to the PTY.
const DETACH_FLUSH_TIMEOUT: Duration = Duration::from_secs(2);
/// Time a dropped [`Terminal`] leaves the child to read just-written input before the hang-up,
/// counted from the last successful PTY write.
const DETACH_GRACE: Duration = Duration::from_millis(50);
/// Poll step of [`wait_detached`].
const DETACH_POLL: Duration = Duration::from_millis(5);

/// Detach-flush workers of dropped [`Terminal`]s (see [`wait_detached`]).
static DETACHING: Mutex<Vec<JoinHandle<()>>> = Mutex::new(Vec::new());

/// Remaining [`DETACH_GRACE`] at `now` after the last PTY write at `last_write`.
fn grace_left(last_write: Option<Instant>, now: Instant) -> Duration {
    last_write.map_or(Duration::ZERO, |at| {
        DETACH_GRACE.saturating_sub(now.saturating_duration_since(at))
    })
}

/// Joins the finished handles in `handles`; true when none is left.
fn prune(handles: &mut Vec<JoinHandle<()>>) -> bool {
    let mut i = 0;
    while i < handles.len() {
        if handles[i].is_finished() {
            let _ = handles.swap_remove(i).join();
        } else {
            i += 1;
        }
    }
    handles.is_empty()
}

/// Polls `handles` until all workers finished or `timeout` passed; true when all finished.
fn wait_handles(handles: &Mutex<Vec<JoinHandle<()>>>, timeout: Duration) -> bool {
    let deadline = Instant::now() + timeout;
    loop {
        if prune(&mut handles.lock().unwrap_or_else(PoisonError::into_inner)) {
            return true;
        }
        let left = deadline.saturating_duration_since(Instant::now());
        if left.is_zero() {
            return false;
        }
        std::thread::sleep(left.min(DETACH_POLL));
    }
}

/// Waits (at most `timeout`) for the detach-flush workers of dropped [`Terminal`]s that still
/// had input in flight, so their bytes reach the children before the process exits. Call it
/// after the UI loop returned.
pub fn wait_detached(timeout: Duration) {
    wait_handles(&DETACHING, timeout);
}

/// Minimum spacing of output-driven repaints while the terminal is visible (one 60 Hz frame).
const VISIBLE_REPAINT: Duration = Duration::from_millis(16);
/// Spacing of output-driven repaints while hidden: enough for title/bell/exit via `poll`.
const HIDDEN_REPAINT: Duration = Duration::from_millis(250);

/// Repaint slots, µs since [`RepaintGate::epoch`].
#[derive(Default)]
struct Slots {
    /// Earliest time the next repaint may happen.
    next: u64,
    /// Time of the last scheduled (delayed) repaint; pending while in the future.
    scheduled: u64,
}

/// Coalesces repaint requests caused by PTY output (shared by the PTY thread's listener
/// and [`Terminal::set_visible`]): at most one repaint per interval. After a quiet interval
/// the repaint is immediate (visible) so typing echo is instant; output within an interval
/// schedules one delayed repaint at the interval's end, which occupies that slot.
pub(crate) struct RepaintGate {
    epoch: Instant,
    visible: AtomicBool,
    slots: Mutex<Slots>,
}

impl RepaintGate {
    fn new() -> Self {
        RepaintGate {
            epoch: Instant::now(),
            visible: AtomicBool::new(true),
            slots: Mutex::new(Slots::default()),
        }
    }

    fn slots(&self) -> MutexGuard<'_, Slots> {
        self.slots.lock().unwrap_or_else(PoisonError::into_inner)
    }

    fn request(&self, ctx: &egui::Context) {
        let now = u64::try_from(self.epoch.elapsed().as_micros()).unwrap_or(u64::MAX);
        self.request_at(now, ctx);
    }

    /// [`Self::request`] at `now` (µs since `epoch`).
    fn request_at(&self, now: u64, ctx: &egui::Context) {
        let visible = self.visible.load(Ordering::Relaxed);
        let interval = if visible {
            VISIBLE_REPAINT
        } else {
            HIDDEN_REPAINT
        };
        let step = interval.as_micros() as u64;
        let mut s = self.slots();
        if s.scheduled > now {
            return;
        }
        if now >= s.next {
            s.next = now.saturating_add(step);
            if visible {
                drop(s);
                ctx.request_repaint();
                return;
            }
            s.scheduled = s.next;
        } else {
            s.scheduled = s.next;
            s.next = s.next.saturating_add(step);
        }
        let delay = Duration::from_micros(s.scheduled - now);
        drop(s);
        ctx.request_repaint_after(delay);
    }

    /// Shown again: a hidden-mode slot must not delay the next output repaint.
    fn reset(&self) {
        *self.slots() = Slots::default();
    }
}

/// Terminal-generated bytes held back by the lone-ESC quiet time.
struct Deferred {
    bytes: Vec<u8>,
    /// A focus report (an opposite report queued later cancels it).
    focus: bool,
}

#[derive(Default)]
struct OutState {
    /// When the last [`Terminal::write`] ended with an ESC byte (cleared by any other write).
    lone_esc_at: Option<Instant>,
    deferred: VecDeque<Deferred>,
    /// Input bytes handed to the event loop so far.
    sent: u64,
    /// Killed or dropped: new bytes are discarded.
    closed: bool,
}

/// The single path of every byte to the PTY (UI thread, PTY thread, clipboard worker).
/// [`Terminal::write`] bytes go out at once. Terminal-generated bytes (query replies, focus
/// reports) never follow a lone ESC within [`LONE_ESC_QUIET`]: they queue in order and go out
/// once the quiet time passed (from [`Terminal::poll`]; a repaint is requested) or directly
/// behind the next write that does not end with ESC. The lock makes "send + update state"
/// atomic, so no reply can slip between a lone ESC and the write ending it.
pub(crate) struct PtyOut {
    sender: OnceLock<EventLoopSender>,
    state: Mutex<OutState>,
    progress: Arc<WriteProgress>,
    ctx: egui::Context,
}

impl PtyOut {
    fn lock(&self) -> MutexGuard<'_, OutState> {
        self.state.lock().unwrap_or_else(PoisonError::into_inner)
    }

    fn send(&self, st: &mut OutState, bytes: Vec<u8>) {
        if let Some(sender) = self.sender.get() {
            st.sent += bytes.len() as u64;
            let _ = sender.send(Msg::Input(Cow::Owned(bytes)));
        }
    }

    fn flush_deferred(&self, st: &mut OutState) {
        while let Some(d) = st.deferred.pop_front() {
            self.send(st, d.bytes);
        }
    }

    /// Remaining quiet time after a write that ended with ESC (forgets the ESC once over).
    fn quiet_left(st: &mut OutState) -> Option<Duration> {
        let left = st
            .lone_esc_at
            .and_then(|at| LONE_ESC_QUIET.checked_sub(at.elapsed()))
            .filter(|d| !d.is_zero());
        if left.is_none() {
            st.lone_esc_at = None;
        }
        left
    }

    fn write(&self, bytes: &[u8]) {
        let mut st = self.lock();
        if st.closed {
            return;
        }
        self.send(&mut st, bytes.to_vec());
        if bytes.last() == Some(&0x1b) {
            st.lone_esc_at = Some(Instant::now());
        } else {
            // The ESC is no longer lone: queued bytes may follow right behind these.
            st.lone_esc_at = None;
            self.flush_deferred(&mut st);
        }
    }

    /// A terminal-generated reply: sent now, or queued behind earlier ones in the quiet time.
    fn reply(&self, bytes: Vec<u8>) {
        self.emit(Deferred {
            bytes,
            focus: false,
        });
    }

    /// A focus report; within the quiet time an out/in pair cancels out.
    fn focus_report(&self, bytes: Vec<u8>) {
        self.emit(Deferred { bytes, focus: true });
    }

    fn emit(&self, d: Deferred) {
        let mut st = self.lock();
        if st.closed {
            return;
        }
        match Self::quiet_left(&mut st) {
            Some(left) => {
                // A queued focus report is always the opposite one (reports fire on changes).
                let queued_focus = d.focus.then(|| st.deferred.iter().position(|q| q.focus));
                match queued_focus.flatten() {
                    Some(pos) => drop(st.deferred.remove(pos)),
                    None => st.deferred.push_back(d),
                }
                self.ctx.request_repaint_after(left);
            }
            None => {
                self.flush_deferred(&mut st);
                self.send(&mut st, d.bytes);
            }
        }
    }

    /// Sends the queue once the quiet time passed (else re-arms a repaint).
    fn flush_due(&self) {
        let mut st = self.lock();
        if st.deferred.is_empty() {
            return;
        }
        match Self::quiet_left(&mut st) {
            Some(left) => self.ctx.request_repaint_after(left),
            None => self.flush_deferred(&mut st),
        }
    }

    /// Msg::Shutdown → the PTY thread stops (dropping queued input) and drops the Pty, which
    /// SIGHUPs the child.
    fn shutdown(&self) {
        if let Some(sender) = self.sender.get() {
            let _ = sender.send(Msg::Shutdown);
        }
    }

    /// Kill: stops at once, discarding queued bytes.
    fn kill(&self) {
        {
            let mut st = self.lock();
            st.closed = true;
            st.deferred.clear();
        }
        self.shutdown();
    }

    /// Detach: stops accepting bytes; true while sent or queued bytes may not have reached
    /// the child yet (see [`Self::finish_detach`]).
    fn close(&self) -> bool {
        let mut st = self.lock();
        st.closed = true;
        !st.deferred.is_empty()
            || self.progress.written() < st.sent
            || !grace_left(self.progress.last_write(), Instant::now()).is_zero()
    }

    /// Blocking (runs on a detach thread): sends the queue after the quiet time, waits until
    /// the event loop wrote everything (bounded) plus a grace after the last write for the
    /// child to read it, then shuts the loop down.
    fn finish_detach(&self) {
        let left = Self::quiet_left(&mut self.lock());
        if let Some(left) = left {
            std::thread::sleep(left);
        }
        let target = {
            let mut st = self.lock();
            self.flush_deferred(&mut st);
            st.sent
        };
        self.progress.wait_for(target, DETACH_FLUSH_TIMEOUT);
        std::thread::sleep(grace_left(self.progress.last_write(), Instant::now()));
        self.shutdown();
    }
}

/// Called from the PTY thread (and from `Term` methods on the UI thread while the Term is
/// locked), so it never locks the Term: PtyWrite goes to [`PtyOut`], everything else to the
/// channel + a coalesced repaint request (query events needing an answer from `poll` repaint
/// at once).
#[derive(Clone)]
pub(crate) struct Listener {
    tx: Sender<Event>,
    out: Arc<PtyOut>,
    ctx: egui::Context,
    gate: Arc<RepaintGate>,
}

impl EventListener for Listener {
    fn send_event(&self, event: Event) {
        match event {
            Event::PtyWrite(s) => self.out.reply(s.into_bytes()),
            Event::Wakeup | Event::MouseCursorDirty | Event::CursorBlinkingChange => {
                self.gate.request(&self.ctx);
            }
            e @ (Event::ColorRequest(..)
            | Event::TextAreaSizeRequest(_)
            | Event::ClipboardLoad(..)) => {
                let _ = self.tx.send(e);
                self.ctx.request_repaint();
            }
            e => {
                let _ = self.tx.send(e);
                self.gate.request(&self.ctx);
            }
        }
    }
}

pub(crate) type SharedTerm = Arc<FairMutex<Term<Listener>>>;

/// One PTY child with its terminal state.
pub struct Terminal {
    pub(crate) term: SharedTerm,
    sender: EventLoopSender,
    /// Every byte to the PTY goes through here.
    out: Arc<PtyOut>,
    rx: Receiver<Event>,
    window_size: WindowSize,
    clipboard: Clipboard,
    palette: Palette,
    tmux_client: bool,
    /// modifyOtherKeys level requested by the child (direct mode), published by the PTY thread.
    modify_other_keys: Arc<AtomicU8>,
    title: Option<String>,
    exit_code: Option<i32>,
    exit_reported: bool,
    shut_down: bool,
    /// When the last byte 0x03 was sent to the PTY (see [`Terminal::last_ctrl_c`]).
    last_ctrl_c: Cell<Option<Instant>>,
    /// User keyboard/paste/IME input is dropped before this instant.
    input_hold: Cell<Option<Instant>>,
    gate: Arc<RepaintGate>,
    /// Per-terminal widget state (selection drag, blink timer, render buffers).
    pub(crate) view: ViewState,
}

impl Terminal {
    /// Spawns the PTY child (alacritty tty + EventLoop thread). Initial size 80x24 until the
    /// first `TerminalView::show`.
    pub fn spawn(
        spec: SpawnSpec,
        opts: TermOptions,
        ctx: egui::Context,
    ) -> std::io::Result<Terminal> {
        let (cols, rows) = (80u16, 24u16);
        let window_size = WindowSize {
            num_lines: rows,
            num_cols: cols,
            cell_width: 8,
            cell_height: 16,
        };
        let (tx, rx) = mpsc::channel();
        let progress = Arc::new(WriteProgress::default());
        let out = Arc::new(PtyOut {
            sender: OnceLock::new(),
            state: Mutex::new(OutState::default()),
            progress: progress.clone(),
            ctx: ctx.clone(),
        });
        let gate = Arc::new(RepaintGate::new());
        let listener = Listener {
            tx,
            out: out.clone(),
            ctx: ctx.clone(),
            gate: gate.clone(),
        };
        let config = Config {
            kitty_keyboard: true,
            osc52: Osc52::CopyPaste,
            scrolling_history: opts.scrollback,
            ..Config::default()
        };
        let term = Term::new(
            config,
            &TermSize::new(usize::from(cols), usize::from(rows)),
            listener.clone(),
        );
        let term = Arc::new(FairMutex::new(term));
        let tty_opts = Options {
            shell: Some(Shell::new(spec.program, spec.args)),
            working_directory: Some(spec.cwd),
            drain_on_exit: true,
            env: spec.env.into_iter().collect::<HashMap<_, _>>(),
        };
        let pty = tty::new(&tty_opts, window_size, 0)?;
        let modify_other_keys = Arc::new(AtomicU8::new(0));
        let pty = TrackedPty::new(pty, modify_other_keys.clone(), progress)?;
        let event_loop =
            EventLoop::new(term.clone(), listener, pty, tty_opts.drain_on_exit, false)?;
        let sender = event_loop.channel();
        // Set before the loop starts parsing, so no PtyWrite can be dropped.
        let _ = out.sender.set(sender.clone());
        // Detached: the thread owns the Pty and drops it (SIGHUP + wait) after Msg::Shutdown.
        drop(event_loop.spawn());
        Ok(Terminal {
            term,
            sender,
            out,
            rx,
            window_size,
            clipboard: opts.clipboard,
            palette: Palette::for_theme(opts.theme),
            tmux_client: spec.tmux_client,
            modify_other_keys,
            title: None,
            exit_code: None,
            exit_reported: false,
            shut_down: false,
            last_ctrl_c: Cell::new(None),
            input_hold: Cell::new(None),
            gate,
            view: ViewState::default(),
        })
    }

    /// Drains pending terminal events: answers ColorRequest / TextAreaSizeRequest /
    /// ClipboardLoad, stores ClipboardStore, records title / bell / exit.
    pub fn poll(&mut self) -> TerminalEvents {
        let mut out = TerminalEvents::default();
        while let Ok(event) = self.rx.try_recv() {
            match event {
                Event::Title(t) => {
                    out.title_changed = Some(t.clone());
                    self.title = Some(t);
                }
                Event::ResetTitle => {
                    self.title = None;
                    out.title_changed = Some(String::new());
                }
                Event::Bell => out.bell = true,
                Event::ClipboardStore(ty, text) => match ty {
                    ClipboardType::Clipboard => self.clipboard.set_text(&text),
                    ClipboardType::Selection => self.clipboard.set_primary(&text),
                },
                Event::ClipboardLoad(ty, fmt) => {
                    // Answered from the clipboard worker once the read completes.
                    if !self.shut_down {
                        let out = self.out.clone();
                        self.clipboard
                            .load(ty == ClipboardType::Selection, move |text| {
                                out.reply(fmt(text.as_deref().unwrap_or("")).into_bytes());
                            });
                    }
                }
                Event::ColorRequest(index, fmt) => {
                    let rgb = {
                        let term = self.term.lock();
                        theme::indexed(term.colors(), &self.palette, index)
                    };
                    self.out.reply(fmt(rgb).into_bytes());
                }
                Event::TextAreaSizeRequest(fmt) => {
                    self.out.reply(fmt(self.window_size).into_bytes());
                }
                Event::PtyWrite(s) => self.out.reply(s.into_bytes()),
                Event::ChildExit(status) => {
                    if self.exit_code.is_none() {
                        self.exit_code = Some(status.code().unwrap_or(-1));
                    }
                }
                Event::Exit => {
                    if self.exit_code.is_none() {
                        self.exit_code = Some(-1);
                    }
                }
                Event::Wakeup | Event::MouseCursorDirty | Event::CursorBlinkingChange => {}
            }
        }
        self.out.flush_due();
        if !self.exit_reported && self.exit_code.is_some() {
            self.exit_reported = true;
            out.exited = self.exit_code;
        }
        out
    }

    /// Last OSC 0/2 title (None after reset).
    pub fn title(&self) -> Option<&str> {
        self.title.as_deref()
    }

    /// Some once the child exited (signal → -1).
    pub fn exit_code(&self) -> Option<i32> {
        self.exit_code
    }

    pub fn is_exited(&self) -> bool {
        self.exit_code.is_some()
    }

    /// Whether the terminal is on screen (default true). While visible, output-driven
    /// repaints are coalesced to one per 16 ms (immediate after a quiet slot, else one delayed
    /// repaint per slot); while hidden, to one delayed repaint per 250 ms (enough for
    /// `poll` to surface title/bell/exit). Query events always repaint at once.
    pub fn set_visible(&self, visible: bool) {
        if self.gate.visible.swap(visible, Ordering::Relaxed) != visible && visible {
            self.gate.reset();
        }
    }

    pub fn set_theme(&mut self, theme: TermTheme) {
        self.palette = Palette::for_theme(theme);
    }

    /// Records keyboard focus. On a change it updates the Term and, when the child enabled
    /// focus reporting (DECSET 1004), writes `ESC[I` / `ESC[O`. [`crate::TerminalView`] uses
    /// the same state, so calling `set_focused(false)` on a tab being hidden and showing it
    /// again later yields exactly one out/in pair.
    ///
    /// Like every terminal-generated byte (query replies too), a report due less than 100 ms
    /// after a [`Self::write`] that ended with ESC is queued until that quiet time passed (sent
    /// by a later [`Self::poll`], which the widget runs every frame; a repaint is requested)
    /// or until the next write that does not end with ESC, right behind its bytes. An out/in
    /// pair falling into the same quiet time cancels out.
    pub fn set_focused(&mut self, focused: bool) {
        if focused == self.view.focused {
            return;
        }
        self.view.focused = focused;
        let mode = {
            let mut term = self.term.lock();
            term.is_focused = focused;
            *term.mode()
        };
        if let Some(bytes) = crate::input::encode_focus(focused, mode) {
            self.out.focus_report(bytes.to_vec());
        }
        self.view.on_focus_change(focused);
    }

    /// Ends the child at once: Msg::Shutdown → the PTY thread drops the Pty, which SIGHUPs the
    /// child. Input not yet written to the PTY is discarded (unlike drop, see [`Terminal`]'s
    /// `Drop`).
    pub fn kill(&mut self) {
        if !self.shut_down {
            self.shut_down = true;
            self.out.kill();
        }
        if self.exit_code.is_none() {
            self.exit_code = Some(-1);
        }
    }

    /// Raw input to the PTY (keys, paste, injected text): sent at once, in order, never held by
    /// [`Self::hold_input_until`] or by the lone-ESC quiet time (the caller's responsibility).
    pub fn write(&self, bytes: &[u8]) {
        if bytes.is_empty() || self.shut_down {
            return;
        }
        if bytes.contains(&0x03) {
            self.note_ctrl_c();
        }
        self.out.write(bytes);
    }

    /// While `Instant::now() < until`, all user keyboard/paste/IME input to this terminal is
    /// dropped (mouse reports, wheel, selection and focus reports are unaffected; [`Self::write`]
    /// is never held). Each call replaces the previous deadline.
    pub fn hold_input_until(&self, until: Instant) {
        self.input_hold.set(Some(until));
    }

    pub(crate) fn input_held(&self) -> bool {
        self.input_hold.get().is_some_and(|u| Instant::now() < u)
    }

    /// Instant the last Ctrl+C was written to the PTY: any 0x03 byte (key input or
    /// [`Self::write`]) or a kitty-encoded Ctrl+C key press. omp exits on two Ctrl+C within
    /// 500 ms; injectors must keep ≥ 650 ms distance.
    pub fn last_ctrl_c(&self) -> Option<Instant> {
        self.last_ctrl_c.get()
    }

    pub(crate) fn note_ctrl_c(&self) {
        self.last_ctrl_c.set(Some(Instant::now()));
    }

    /// Visible rows of the active screen (viewport at the bottom, i.e. ignoring the local
    /// scrollback position): wide-char spacers skipped, combining marks kept, trailing blanks
    /// trimmed.
    pub fn screen_text(&self) -> ScreenText {
        let term = self.term.lock();
        let grid = term.grid();
        let rows = term.screen_lines();
        let mut lines = Vec::with_capacity(rows);
        for line in 0..rows {
            let mut out = String::with_capacity(term.columns());
            for cell in &grid[Line(line as i32)][..] {
                if cell
                    .flags
                    .intersects(Flags::WIDE_CHAR_SPACER | Flags::LEADING_WIDE_CHAR_SPACER)
                {
                    continue;
                }
                out.push(cell.c);
                if let Some(marks) = cell.zerowidth() {
                    out.extend(marks.iter());
                }
            }
            out.truncate(out.trim_end().len());
            lines.push(out);
        }
        let cursor = grid.cursor.point;
        ScreenText {
            lines,
            cursor_row: usize::try_from(cursor.line.0).unwrap_or(0),
            cursor_col: cursor.column.0,
        }
    }

    pub(crate) fn palette(&self) -> &Palette {
        &self.palette
    }

    pub(crate) fn clipboard(&self) -> &Clipboard {
        &self.clipboard
    }

    /// Non-kitty key-encoding rules: tmux always speaks modifyOtherKeys 2 to us; a direct child
    /// gets rule 2 while it has requested level ≥ 2.
    pub(crate) fn key_rules(&self) -> KeyRules {
        if self.tmux_client {
            KeyRules::Tmux
        } else if self.modify_other_keys.load(Ordering::Relaxed) >= 2 {
            KeyRules::ModifyOtherKeys
        } else {
            KeyRules::Legacy
        }
    }

    pub(crate) fn mode(&self) -> TermMode {
        *self.term.lock().mode()
    }

    /// Resizes Term + PTY (SIGWINCH) when the grid or the cell pixel size changed.
    pub(crate) fn resize(&mut self, cols: u16, rows: u16, cell_width: u16, cell_height: u16) {
        let ws = WindowSize {
            num_lines: rows,
            num_cols: cols,
            cell_width,
            cell_height,
        };
        let old = self.window_size;
        if (old.num_lines, old.num_cols, old.cell_width, old.cell_height)
            == (ws.num_lines, ws.num_cols, ws.cell_width, ws.cell_height)
        {
            return;
        }
        self.window_size = ws;
        if (old.num_lines, old.num_cols) != (rows, cols) {
            self.term
                .lock()
                .resize(TermSize::new(usize::from(cols), usize::from(rows)));
        }
        if !self.shut_down {
            let _ = self.sender.send(Msg::Resize(ws));
        }
    }
}

impl Drop for Terminal {
    /// Detaches without blocking: every byte already passed to [`Terminal::write`] (and
    /// every queued reply, after the lone-ESC quiet time) still reaches the child before the
    /// PTY thread hangs up (SIGHUP reaches only the tmux client). When bytes are in flight a
    /// short-lived thread waits for the event loop to write them (bounded by 2 s) plus 50 ms
    /// after the last write for the child to read them, then sends Msg::Shutdown. The thread
    /// is registered for [`wait_detached`].
    fn drop(&mut self) {
        if self.shut_down {
            return;
        }
        self.shut_down = true;
        if !self.out.close() {
            self.out.shutdown();
            return;
        }
        let out = self.out.clone();
        let spawned = std::thread::Builder::new()
            .name("deck-term-detach".into())
            .spawn(move || out.finish_detach());
        match spawned {
            Ok(handle) => {
                let mut pending = DETACHING.lock().unwrap_or_else(PoisonError::into_inner);
                prune(&mut pending);
                pending.push(handle);
            }
            Err(_) => self.out.shutdown(),
        }
    }
}

