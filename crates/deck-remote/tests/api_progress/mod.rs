fn build() -> Value {
    let mut messages: Vec<Value> = events().into_iter().enumerate().map(|(i,e)| json!({"type":"event","case":format!("live progress goal status {i}"),"json":json_text(&e)})).collect();
    messages.push(
        json!({"type":"welcome","case":"welcome with progress","json":json_text(&welcome())}),
    );
    json!({"description":"Feature-gated live todo/goal progress. Every task and goal status, canonical event and welcome JSON. Earlier vectors remain unchanged. Generated by tests/api_progress/mod.rs.","protocol":PROTOCOL,"features":[FEATURE_S4,FEATURE_PROGRESS],"messages":messages,"rejected_requests":[]})
}

#[test]
fn progress_vectors_match() {
    let text = serde_json::to_string_pretty(&build()).unwrap() + "\n";
    if std::env::var_os("OMPDECK_WRITE_VECTORS").is_some() {
        std::fs::write(PATH, &text).unwrap();
    }
    assert_eq!(
        std::fs::read_to_string(PATH).expect("api-progress.json (OMPDECK_WRITE_VECTORS=1)"),
        text
    );
}

#[test]
fn progress_messages_round_trip() {
    let file: Value = serde_json::from_str(&std::fs::read_to_string(PATH).unwrap()).unwrap();
    for (m, event) in file["messages"].as_array().unwrap().iter().zip(events()) {
        let text = m["json"].as_str().unwrap();
        assert_eq!(serde_json::from_str::<Event>(text).unwrap(), event);
        assert_eq!(json_text(&event), text);
    }
    let text = file["messages"].as_array().unwrap().last().unwrap()["json"]
        .as_str()
        .unwrap();
    assert_eq!(serde_json::from_str::<Welcome>(text).unwrap(), welcome());
    assert_eq!(json_text(&welcome()), text);
}

#[test]
fn progress_is_omitted_when_absent() {
    let Event::Feed {
        value: FeedValue::Live { mut sessions, .. },
        ..
    } = events().remove(0)
    else {
        panic!("live")
    };
    let session = &mut sessions[0];
    session.progress = None;
    let text = json_text(session);
    assert!(
        serde_json::from_str::<Value>(&text)
            .unwrap()
            .get("progress")
            .is_none()
    );
    assert_eq!(
        serde_json::from_str::<LiveSession>(&text).unwrap(),
        *session
    );
}

#[test]
fn progress_decode_bounds_unicode_and_unknown_statuses() {
    let task = json!({"content":"🦀".repeat(201),"status":"future"});
    let phase = json!({"name":"é".repeat(81),"tasks":vec![task;81]});
    let value = json!({"phases":vec![phase;17],"goal":{"objective":"x".repeat(401),"status":"future","tokens_used":1,"token_budget":null,"time_used_seconds":2},"truncated":false});
    let progress: ProgressView = serde_json::from_value(value).unwrap();
    assert!(progress.truncated);
    assert_eq!(progress.phases.len(), 16);
    assert_eq!(
        progress.phases.iter().map(|p| p.tasks.len()).sum::<usize>(),
        80
    );
    assert_eq!(progress.phases[0].name.chars().count(), 80);
    assert_eq!(progress.phases[0].tasks[0].content.chars().count(), 200);
    assert!(progress.phases[0].tasks[0].content.ends_with(CUT_MARK));
    assert_eq!(
        progress.phases[0].tasks[0].status,
        ProgressTaskStatus::Unknown
    );
    let goal = progress.goal.unwrap();
    assert_eq!(goal.objective.chars().count(), 400);
    assert_eq!(goal.status, ProgressGoalStatus::Unknown);
}
