use super::*;

pub const PATH: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/tests/vectors/api-treenav.json"
);

fn message<T>(kind: &str, case: &str, value: &T) -> Value
where
    T: serde::Serialize + serde::de::DeserializeOwned + PartialEq + std::fmt::Debug,
{
    let text = json_text(value);
    let decoded: T = serde_json::from_str(&text).unwrap();
    assert_eq!(&decoded, value, "{case}");
    assert_eq!(json_text(&decoded), text, "{case}");
    json!({"type": kind, "case": case, "json": text})
}

fn tree(id: u64, cursor: Option<&str>, at_leaf: bool, limit: u32) -> Request {
    Request {
        id,
        seq: None,
        op: Op::Tree {
            session: SESSION.into(),
            filter: TreeFilter::Conversation,
            cursor: cursor.map(str::to_owned),
            limit,
            at_leaf,
        },
    }
}

fn node(first: bool) -> TreeNode {
    TreeNode {
        id: if first { "entry-3" } else { "entry-4" }.into(),
        parent: (!first).then(|| "entry-3".into()),
        kind: TreeNodeKind::Assistant,
        subtype: None,
        at_unix_ms: None,
        text: "Continue from here".into(),
        has_text: true,
        stop_reason: None,
        label: None,
        forkable: true,
        cost_before: None,
        cost_incomplete: false,
    }
}

fn page(id: u64, first: bool) -> Reply {
    Reply {
        id,
        result: ReplyResult::Ok(Resp::Tree {
            nodes: vec![node(first)],
            active_leaf: Some("entry-4".into()),
            next_cursor: Some(if first { "t-1" } else { "t-2" }.into()),
            truncated: false,
            prev_cursor: (!first).then(|| "b-1".into()),
            total: Some(7),
        }),
    }
}

fn outcome(seq: u64, result: DoneView) -> Event {
    Event::Outcome {
        seq,
        outcome: OutcomeView::Done { result },
    }
}

fn build() -> Value {
    let features = [FEATURE_S4, FEATURE_TREE_NAV];
    let mut welcome = welcomes().pop().unwrap().1;
    welcome.features = features.map(str::to_owned).into();
    let messages = [
        message("welcome", "welcome with tree_nav", &welcome),
        message("request", "tree around the leaf", &tree(1, None, true, 1)),
        message(
            "request",
            "tree backward cursor",
            &tree(2, Some("b-1"), false, 1),
        ),
        message("reply", "tree page with both cursors", &page(1, false)),
        message("reply", "first tree page omits prev_cursor", &page(2, true)),
        message(
            "event",
            "navigate before a prompt with editor text",
            &outcome(
                401,
                DoneView::Moved {
                    leaf: Some("entry-4".into()),
                    before_prompt: true,
                    editor_text: Some("Rework this\nありがとう 🧭".into()),
                    dropped_images: 2,
                    message: None,
                },
            ),
        ),
        message(
            "event",
            "navigate before the first prompt with an older extension",
            &outcome(
                402,
                DoneView::Moved {
                    leaf: None,
                    before_prompt: true,
                    editor_text: None,
                    dropped_images: 0,
                    message: None,
                },
            ),
        ),
        message(
            "event",
            "navigate already at the target",
            &outcome(
                403,
                DoneView::Moved {
                    leaf: Some("entry-4".into()),
                    before_prompt: false,
                    editor_text: None,
                    dropped_images: 0,
                    message: Some("Already at this point".into()),
                },
            ),
        ),
    ];
    json!({
        "description": "Additive phone tree paging and navigation outcomes. Earlier vectors remain unchanged. Generated by tests/api_treenav/mod.rs.",
        "protocol": PROTOCOL,
        "features": features,
        "messages": messages,
        "rejected_requests": [],
    })
}

#[test]
fn treenav_vectors_match() {
    let text = serde_json::to_string_pretty(&build()).unwrap() + "\n";
    if std::env::var_os("OMPDECK_WRITE_VECTORS").is_some() {
        std::fs::write(PATH, &text).unwrap();
    }
    assert_eq!(
        std::fs::read_to_string(PATH).expect("api-treenav.json (OMPDECK_WRITE_VECTORS=1)"),
        text
    );
}

#[test]
fn tree_request_flag_defaults_to_false_and_preserves_bounds() {
    let omitted = tree(1, None, false, 1);
    let text = json_text(&omitted);
    assert!(!text.contains("at_leaf"));
    assert_eq!(Request::parse(text.as_bytes()).unwrap(), omitted);
    let explicit = |flag| text.replace("\"limit\":1", &format!("\"limit\":1,\"at_leaf\":{flag}"));
    assert_eq!(
        Request::parse(explicit("false").as_bytes()).unwrap(),
        omitted
    );
    for malformed in ["null", "1", "\"true\""] {
        assert!(matches!(
            Request::parse(explicit(malformed).as_bytes()),
            Err(RequestError::Bad { id: 1, .. })
        ));
    }
    assert!(tree(1, None, true, MAX_TREE_LIMIT).op.check().is_ok());
    assert!(tree(1, None, true, MAX_TREE_LIMIT + 1).op.check().is_err());
}

#[test]
fn tree_reply_explicit_nulls_are_accepted_but_not_serialized() {
    let reply: Reply = serde_json::from_str(
        r#"{"id":1,"ok":{"type":"tree","nodes":[],"active_leaf":null,"next_cursor":null,"truncated":false,"prev_cursor":null,"total":null}}"#,
    )
    .unwrap();
    assert_eq!(
        json_text(&reply),
        r#"{"id":1,"ok":{"type":"tree","nodes":[],"active_leaf":null,"next_cursor":null,"truncated":false}}"#
    );
}
